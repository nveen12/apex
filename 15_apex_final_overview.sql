            '                   service_name_ziel  = :P11_SERVICE_NAME_ZIEL,',
            '                   apex_version       = :P11_APEX_VERSION,',
            '                   status             = :P11_STATUS,',
            '                   url                = :P11_URL',
            '            where  overview_id        = :P11_OVERVIEW_ID;',
            '        end if;',
            '    end if;',
            '',
            '    commit;',
            '    apex_util.redirect_url(''f?p='' || v(''APP_ID'') || '':1:'' || v(''APP_SESSION'') || ''::NO:::'' );',
            'end;')),
        p_process_when            => 'SAVE,DELETE',
        p_process_when_type       => 'REQUEST_IN_CONDITION',
        p_error_display_location  => 'INLINE_IN_NOTIFICATION',
        p_process_success_message => 'Eintrag gespeichert.',
        p_internal_uid            => 91500000000001131);

    -- Remove old visible pages. Page 9 is intentionally kept as detail page.
    for p in 2 .. 8 loop
        begin
            wwv_flow_imp_page.remove_page(p_flow_id => l_app_id, p_page_id => p);
        exception
            when others then
                null;
        end;
    end loop;

    -- Hide stale imported navigation entries for removed pages.
    -- wwv_flow_imp_shared has no delete API for list items, but importing the
    -- same item id with ITEM_DISPLAYED = N updates the item cleanly.
    for r in (
        select list_entry_id, entry_text, entry_target, display_sequence
        from   apex_application_list_entries
        where  application_id = l_app_id
        and    list_name = 'Navigation Menu'
        and    (
                  entry_text in ('Home',
                                 'Fachverfahren',
                                 'Caesar Orders',
                                 'Checkliste',
                                 'Service Name Audit',
                                 'Server Inventory')
               or regexp_like(entry_target, '[:.]([2-8])[:.]')
               )
    ) loop
        begin
            wwv_flow_imp_shared.create_list_item(
                p_id                         => r.list_entry_id,
                p_list_id                    => l_nav_list_id,
                p_list_item_type             => 'LINK',
                p_list_item_status           => 'PUBLIC',
                p_item_displayed             => 'N',
                p_list_item_display_sequence => nvl(r.display_sequence, 900),
                p_list_item_link_text        => r.entry_text,
                p_list_item_link_target      => r.entry_target,
                p_list_item_current_type     => 'TARGET_PAGE');
        exception
            when others then
                null;
        end;
    end loop;

    -- Rename/repoint existing Page 1 navigation entry if it exists.
    for r in (
        select list_entry_id
        from   apex_application_list_entries
        where  application_id = l_app_id
        and    list_name = 'Navigation Menu'
        and    entry_target like '%:1:%'
    ) loop
        wwv_flow_imp_shared.set_list_item_sequence(
            p_id            => r.list_entry_id,
            p_item_sequence => 10);
        wwv_flow_imp_shared.set_list_item_link_text(
            p_id        => r.list_entry_id,
            p_link_text => 'APEX Migration ' || unistr('\00DC') || 'bersicht');
        wwv_flow_imp_shared.set_list_item_link_target(
            p_id          => r.list_entry_id,
            p_link_target => 'f?p=&APP_ID.:1:&APP_SESSION.::&DEBUG.:::');
    end loop;

    -- Ensure Live Vergleich has a visible navigation entry.
    begin
        wwv_flow_imp_shared.create_list_item(
            p_id                          => wwv_flow_imp.id(91500000000000050),
            p_list_id                     => l_nav_list_id,
            p_list_item_type              => 'LINK',
            p_list_item_status            => 'PUBLIC',
            p_item_displayed              => 'Y',
            p_list_item_display_sequence  => 20,
            p_list_item_link_text         => 'Live Vergleich',
            p_list_item_link_target       => 'f?p=&APP_ID.:10:&APP_SESSION.::&DEBUG.:::',
            p_list_item_icon              => 'fa-search',
            p_list_item_current_type      => 'TARGET_PAGE',
            p_list_item_current_for_pages => '10');
    exception
        when others then
            null;
    end;

    wwv_flow_imp.import_end(p_auto_install_sup_obj => false);
    commit;
end;
